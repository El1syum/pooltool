import assert from 'node:assert/strict'
import { mkdir } from 'node:fs/promises'
import path from 'node:path'
import { pathToFileURL } from 'node:url'
const modulePath = process.env.PLAYWRIGHT_MODULE || 'playwright'
const playwright = await import(path.isAbsolute(modulePath) ? pathToFileURL(modulePath).href : modulePath)
const engine = process.env.BROWSER || 'chromium'
const base = process.env.POOLTOOL_URL || 'http://127.0.0.1:4321'
const artifacts = process.env.ARTIFACT_DIR || path.resolve('tests/artifacts/club-menu')
await mkdir(artifacts, { recursive: true })
const browser = await playwright[engine].launch({ headless: true })
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } })
const errors = []
page.on('pageerror', error => errors.push(error.message))
try {
  await page.goto(`${base}/tests/club-menu-fixture.html`)
  await page.getByRole('heading', { name: 'Pooltool', exact: true }).waitFor()
  await page.evaluate(() => document.fonts.ready)
  await page.screenshot({ path: path.join(artifacts, 'home-1440.png') })
  const main = await page.locator('.club-main-menu').boundingBox()
  assert.equal(main.width, 480)
  assert.equal(main.x, 480)
  await page.getByRole('button', { name: 'Играть', exact: true }).click()
  await page.getByRole('heading', { name: 'Играть', exact: true }).waitFor()
  await page.screenshot({ path: path.join(artifacts, 'play-1440.png') })
  const botEntry = page.getByRole('button', { name: 'Тренировка с ботом', exact: true })
  assert.equal(await botEntry.evaluate(node => node.classList.contains('club-action') && !node.classList.contains('club-text-button')), true)
  const botBounds = await botEntry.boundingBox()
  const opponentBounds = await page.getByRole('button', { name: 'Случайный противник', exact: true }).boundingBox()
  assert.equal(botBounds.width, opponentBounds.width)
  assert.equal(botBounds.height, opponentBounds.height)
  const botIcon = await botEntry.locator('img').first().evaluate(async image => {
    await image.decode()
    const rect = image.getBoundingClientRect()
    return { source: image.src.split('/').at(-1), native: [image.naturalWidth, image.naturalHeight], slot: [rect.width, rect.height], fit: getComputedStyle(image).objectFit }
  })
  assert.deepEqual(botIcon, { source: 'bot.svg', native: [14, 18], slot: [20, 20], fit: 'scale-down' })
  await botEntry.focus()
  await page.keyboard.press('Enter')
  await page.getByRole('heading', { name: 'Тренировка с ботом', exact: true }).waitFor()
  await page.getByRole('combobox', { name: 'Сложность', exact: true }).selectOption('hard')
  await page.getByRole('combobox', { name: 'Время на ход', exact: true }).selectOption('90')
  await page.getByRole('button', { name: 'Играть с ботом', exact: true }).click()
  assert.deepEqual(await page.evaluate(() => window.lastFixtureBot), { difficulty: 'hard', turnSeconds: 90 })
  await page.getByRole('button', { name: 'Назад', exact: true }).click()
  await page.evaluate(() => window.clubFixture.busy = true)
  assert.equal(await botEntry.isDisabled(), true)
  await page.evaluate(() => { window.clubFixture.busy = false; window.clubFixture.connected = false })
  assert.equal(await botEntry.isDisabled(), true)
  await page.evaluate(() => window.clubFixture.connected = true)
  assert.equal(await botEntry.isEnabled(), true)
  await page.getByRole('button', { name: 'Игра с другом', exact: true }).click()
  await page.getByRole('button', { name: 'Настройки игры', exact: true }).click()
  await page.getByRole('combobox').selectOption('90')
  await page.getByRole('button', { name: 'Сохранить правила', exact: true }).click()
  await page.getByRole('button', { name: 'Создать игру', exact: true }).click()
  await page.getByText('90 секунд на удар', { exact: false }).waitFor()
  await page.getByRole('button', { name: 'Готов', exact: true }).click()
  await page.getByRole('button', { name: 'Отменить готовность', exact: true }).waitFor()
  await page.screenshot({ path: path.join(artifacts, 'lobby-1440.png') })
  await page.getByRole('button', { name: 'Выйти из комнаты', exact: true }).click()
  await page.getByRole('heading', { name: 'Игра с другом', exact: true }).waitFor()
  assert.equal(await page.evaluate(() => window.clubFixture.room), null, 'Leaving the room must return to its parent without retaining membership')
  await page.getByRole('button', { name: 'Присоединиться', exact: true }).click()
  await page.getByLabel('Код комнаты', { exact: true }).fill('ab12xy')
  assert.equal(await page.getByLabel('Код комнаты', { exact: true }).inputValue(), 'AB12XY')
  await page.getByRole('button', { name: 'Присоединиться к игре', exact: true }).click()
  assert.deepEqual(await page.evaluate(() => window.lastFixtureJoin), { spectate: false, code: 'AB12XY' })
  await page.screenshot({ path: path.join(artifacts, 'join-1440.png') })
  await page.getByRole('button', { name: 'В главное меню', exact: true }).click()
  await page.getByRole('button', { name: 'Настройки', exact: true }).click()
  assert.equal(await page.getByTestId('graphics-summary').textContent(), 'Средняя')
  assert.equal(await page.getByTestId('volume-summary').textContent(), '50%')
  await page.getByRole('dialog').locator('img').evaluateAll(images => Promise.all(images.map(image => image.decode())))
  const settingAssets = await page.getByRole('dialog').locator('nav[aria-label="Разделы настроек"] .club-action').evaluateAll(buttons => buttons.slice(0, 3).map(button => {
    const images = [...button.querySelectorAll('img')]
    return images.map(image => ({ name: image.src.split('/').at(-1), width: image.getBoundingClientRect().width, height: image.getBoundingClientRect().height, loaded: image.complete && image.naturalWidth > 0 }))
  }))
  assert.deepEqual(settingAssets, ['monitor.svg', 'volume.svg', 'mouse.svg'].map(name => [{ name, width: 20, height: 20, loaded: true }]), 'Figma settings slots contain their original native-size icons and live summaries, not additional chevrons')
  await page.screenshot({ path: path.join(artifacts, 'settings-index-1440.png') })
  await page.getByRole('button', { name: 'Графика', exact: true }).click()
  await page.getByLabel('Качество графики', { exact: true }).selectOption('high')
  assert.equal(await page.evaluate(() => window.clubFixture.settings.quality), 'high')
  await page.getByText('Дополнительные параметры графики', { exact: true }).click()
  await page.getByRole('switch', { name: 'Номера луз', exact: true }).click()
  assert.equal(await page.evaluate(() => window.clubFixture.settings.showPocketLabels), false)
  await page.evaluate(() => window.clubFixture.searchMode = 'ranked')
  assert.equal(await page.getByRole('switch', { name: 'Линия прицеливания', exact: true }).isDisabled(), true)
  await page.screenshot({ path: path.join(artifacts, 'graphics-1440.png') })
  await page.getByRole('button', { name: 'Применить', exact: true }).click()
  await page.getByRole('button', { name: 'Настройки', exact: true }).click()
  assert.equal(await page.getByTestId('graphics-summary').textContent(), 'Высокая', 'Summary follows the actual selected quality after reopening')
  await page.getByRole('button', { name: 'Управление', exact: true }).click()
  await page.getByLabel('Чувствительность', { exact: true }).fill('1.8')
  assert.equal(await page.evaluate(() => window.clubFixture.settings.sensitivity), 1.8)
  await page.screenshot({ path: path.join(artifacts, 'controls-1440.png') })
  await page.getByRole('button', { name: 'Закрыть настройки', exact: true }).click()
  for (const width of [320, 390, 768]) {
    await page.setViewportSize({ width, height: 844 })
    await page.evaluate(() => { window.clubFixture.view = 'menu' })
    await page.getByRole('heading', { name: 'Pooltool', exact: true }).waitFor()
    const sizes = await page.evaluate(() => ({ viewport: innerWidth, scroll: document.documentElement.scrollWidth, shell: document.querySelector('.club-shell').scrollWidth }))
    assert.ok(sizes.scroll <= sizes.viewport + 1, JSON.stringify(sizes))
    assert.ok(sizes.shell <= sizes.viewport + 1, JSON.stringify(sizes))
    await page.screenshot({ path: path.join(artifacts, `home-${width}.png`) })
    const header = await page.locator('.club-header').evaluate(el => {
      const [brand, account] = [...el.children].map(x => x.getBoundingClientRect())
      return { brandRight: brand.right, accountLeft: account.left }
    })
    assert.ok(header.brandRight < header.accountLeft, JSON.stringify(header))
    await page.getByRole('button', { name: 'Играть', exact: true }).click()
    const mobileBot = page.getByRole('button', { name: 'Тренировка с ботом', exact: true })
    const mobileAction = await page.getByRole('button', { name: 'Случайный противник', exact: true }).boundingBox()
    const mobileBotBounds = await mobileBot.boundingBox()
    assert.equal(mobileBotBounds.width, mobileAction.width)
    assert.equal(mobileBotBounds.height, mobileAction.height)
    assert.ok(mobileBotBounds.height >= (width <= 480 ? 56 : 62))
    await mobileBot.scrollIntoViewIfNeeded()
    await page.screenshot({ path: path.join(artifacts, `play-bot-${width}.png`) })
    await page.getByRole('button', { name: 'Назад', exact: true }).click()
    await page.getByRole('button', { name: 'Профиль', exact: true }).click()
    const profileSize = await page.evaluate(() => ({ viewport: innerWidth, shell: document.querySelector('.club-shell').scrollWidth }))
    assert.ok(profileSize.shell <= profileSize.viewport + 1, JSON.stringify(profileSize))
    await page.screenshot({ path: path.join(artifacts, `profile-${width}.png`) })
    await page.getByRole('button', { name: 'В главное меню', exact: true }).click()
    await page.getByRole('button', { name: 'Настройки', exact: true }).click()
    const summaryBounds = await page.getByTestId('graphics-summary').evaluate(node => {
      const bounds = node.getBoundingClientRect(), parent = node.closest('button').getBoundingClientRect()
      return { left: bounds.left, right: bounds.right, buttonLeft: parent.left, buttonRight: parent.right }
    })
    assert.ok(summaryBounds.left >= summaryBounds.buttonLeft && summaryBounds.right <= summaryBounds.buttonRight, JSON.stringify(summaryBounds))
    await page.getByRole('button', { name: 'Управление', exact: true }).click()
    const controlSize = await page.evaluate(() => ({ viewport: innerWidth, shell: document.querySelector('.club-settings-shell').scrollWidth }))
    assert.ok(controlSize.shell <= controlSize.viewport + 1, JSON.stringify(controlSize))
    await page.screenshot({ path: path.join(artifacts, `controls-${width}.png`) })
    await page.getByRole('button', { name: 'Закрыть настройки', exact: true }).click()
  }
  assert.deepEqual(errors, [])
  console.log(JSON.stringify({ engine, tests: 'navigation, full-size bot action/native SVG/difficulty/start event/keyboard/busy-offline lock, room, code, ready, live Figma settings summaries and original icon geometry, ranked lock, 320/390/768/1440 layouts', jsErrors: errors.length }))
} finally { await browser.close() }
